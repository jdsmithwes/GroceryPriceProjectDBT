-- Grocery ops layer — part 4: hard-failure alerts (serverless, hourly).
-- The tasks (03) wake four times a week; these alerts catch the few things
-- that should not wait: a scheduled job that failed or never started, a
-- failed task, a resource monitor past 75%. Serverless alerts bill seconds of
-- compute, so hourly is cheap; a warehouse-backed 15-minute alert would cost
-- ~1.6 credits a day and was rejected.
--
-- Each alert emails Proton and writes an OPS_EVENT (SOURCE = alert) with a
-- fingerprint, so the sensors and agents see the same finding and do not
-- raise it twice. Created SUSPENDED; the PROD ONLY section resumes them after
-- each has been fired once by hand (EXECUTE ALERT).
--
-- Sandbox variant: sed -E 's/GROCERY_OPS([^_A-Za-z0-9]|$)/GROCERY_DEV_OPS\1/g; /^-- PROD ONLY/,$d'

USE ROLE ACCOUNTADMIN;

-- Alert helper: raise (or refresh) an alert event and email once per fingerprint per day
CREATE OR REPLACE PROCEDURE GROCERYDBTPROJECT.GROCERY_OPS.SP_RAISE_ALERT(CHECK_NAME VARCHAR, DOMAIN VARCHAR, SUBJECT VARCHAR, MESSAGE VARCHAR)
RETURNS VARCHAR LANGUAGE SQL
COMMENT = 'Used by the hourly alerts: inserts/refreshes an OPS_EVENT (SOURCE=alert) and emails Proton at most once per fingerprint per 24 h.'
EXECUTE AS OWNER
AS
$$
DECLARE fp VARCHAR := :CHECK_NAME || '|' || :SUBJECT || '|' || CURRENT_DATE()::VARCHAR; already INT; sent BOOLEAN;
BEGIN
    SELECT COUNT(*) INTO :already FROM GROCERYDBTPROJECT.GROCERY_OPS.OPS_EVENT WHERE FINGERPRINT = :fp AND EMAILED_AT >= DATEADD(hour, -24, CURRENT_TIMESTAMP());
    MERGE INTO GROCERYDBTPROJECT.GROCERY_OPS.OPS_EVENT t USING (SELECT :fp AS FP) s ON t.FINGERPRINT = s.FP AND t.STATUS IN ('open', 'acked')
    WHEN MATCHED THEN UPDATE SET LAST_SEEN_AT = CURRENT_TIMESTAMP(), MESSAGE = :MESSAGE
    WHEN NOT MATCHED THEN INSERT (DOMAIN, CHECK_NAME, SEVERITY, FINGERPRINT, SUBJECT, MESSAGE, SOURCE, PERIOD_TS) VALUES (:DOMAIN, :CHECK_NAME, 'CRIT', :fp, :SUBJECT, :MESSAGE, 'alert', CURRENT_TIMESTAMP());
    IF (already = 0) THEN
        CALL GROCERYDBTPROJECT.GROCERY_OPS.SP_SEND_OPS_EMAIL(:DOMAIN, 'CRIT', :CHECK_NAME || ': ' || :SUBJECT, :MESSAGE || '\n\nRaised by an hourly alert. The next ops agent run will explain it; see GROCERY_OPS.OPS_EVENT.') INTO :sent;
        UPDATE GROCERYDBTPROJECT.GROCERY_OPS.OPS_EVENT SET EMAILED_AT = CURRENT_TIMESTAMP() WHERE FINGERPRINT = :fp;
        RETURN 'raised+emailed';
    END IF;
    RETURN 'refreshed';
END;
$$;

-- 1. A scheduled ingestion run failed, or the Friday run is absent by Saturday 03:00 ET
CREATE OR REPLACE ALERT GROCERYDBTPROJECT.GROCERY_OPS.ALERT_INGESTION_RUN
    SCHEDULE = '60 minute'
    -- Hourly: failed job-run rows in the last 24 h, or a due Friday/Saturday slot with no run (V_CHECK_EXPECTED_RUNS)
    IF (EXISTS (SELECT 1 FROM GROCERYDBTPROJECT.GROCERY_OPS.V_CHECK_EXPECTED_RUNS
                WHERE SEVERITY = 'CRIT' AND PERIOD_TS >= DATEADD(day, -3, CURRENT_TIMESTAMP())))
    THEN
        CALL GROCERYDBTPROJECT.GROCERY_OPS.SP_RAISE_ALERT('run_missing', 'ingestion',
            (SELECT LISTAGG(SUBJECT || ' ' || PERIOD_KEY, ', ') FROM GROCERYDBTPROJECT.GROCERY_OPS.V_CHECK_EXPECTED_RUNS WHERE SEVERITY = 'CRIT' AND PERIOD_TS >= DATEADD(day, -3, CURRENT_TIMESTAMP())),
            (SELECT LISTAGG(MESSAGE, '\n') FROM GROCERYDBTPROJECT.GROCERY_OPS.V_CHECK_EXPECTED_RUNS WHERE SEVERITY = 'CRIT' AND PERIOD_TS >= DATEADD(day, -3, CURRENT_TIMESTAMP())));

-- 2. A Snowflake task in the project failed in the last 2 hours
CREATE OR REPLACE ALERT GROCERYDBTPROJECT.GROCERY_OPS.ALERT_TASK_FAILED
    SCHEDULE = '60 minute'
    -- Hourly: FAILED tasks in GROCERY_ML / GROCERY_OPS over the last 2 h (ACCOUNT_USAGE.TASK_HISTORY)
    IF (EXISTS (SELECT 1 FROM SNOWFLAKE.ACCOUNT_USAGE.TASK_HISTORY
                WHERE DATABASE_NAME = 'GROCERYDBTPROJECT' AND SCHEMA_NAME IN ('GROCERY_ML', 'GROCERY_OPS')
                  AND STATE IN ('FAILED', 'FAILED_AND_AUTO_SUSPENDED') AND SCHEDULED_TIME >= DATEADD(hour, -2, CURRENT_TIMESTAMP())))
    THEN
        CALL GROCERYDBTPROJECT.GROCERY_OPS.SP_RAISE_ALERT('task_failed_or_missed', 'performance',
            (SELECT LISTAGG(DISTINCT SCHEMA_NAME || '.' || NAME, ', ') FROM SNOWFLAKE.ACCOUNT_USAGE.TASK_HISTORY WHERE DATABASE_NAME = 'GROCERYDBTPROJECT' AND SCHEMA_NAME IN ('GROCERY_ML', 'GROCERY_OPS') AND STATE IN ('FAILED', 'FAILED_AND_AUTO_SUSPENDED') AND SCHEDULED_TIME >= DATEADD(hour, -2, CURRENT_TIMESTAMP())),
            (SELECT LISTAGG(SCHEMA_NAME || '.' || NAME || ': ' || COALESCE(ERROR_MESSAGE, STATE), '\n') FROM SNOWFLAKE.ACCOUNT_USAGE.TASK_HISTORY WHERE DATABASE_NAME = 'GROCERYDBTPROJECT' AND SCHEMA_NAME IN ('GROCERY_ML', 'GROCERY_OPS') AND STATE IN ('FAILED', 'FAILED_AND_AUTO_SUSPENDED') AND SCHEDULED_TIME >= DATEADD(hour, -2, CURRENT_TIMESTAMP())));

-- 3. Any project resource monitor at or past 75% of its month
CREATE OR REPLACE ALERT GROCERYDBTPROJECT.GROCERY_OPS.ALERT_BUDGET
    SCHEDULE = '60 minute'
    -- Hourly: a GROCERY_* resource monitor at >= 75% of quota (V_CHECK_MONITORS)
    IF (EXISTS (SELECT 1 FROM GROCERYDBTPROJECT.GROCERY_OPS.V_CHECK_MONITORS WHERE METRIC_VALUE >= 75))
    THEN
        CALL GROCERYDBTPROJECT.GROCERY_OPS.SP_RAISE_ALERT('resource_monitor_used', 'cost',
            (SELECT LISTAGG(SUBJECT, ', ') FROM GROCERYDBTPROJECT.GROCERY_OPS.V_CHECK_MONITORS WHERE METRIC_VALUE >= 75),
            (SELECT LISTAGG(MESSAGE, '\n') FROM GROCERYDBTPROJECT.GROCERY_OPS.V_CHECK_MONITORS WHERE METRIC_VALUE >= 75));

-- PROD ONLY ------------------------------------------------------------------
GRANT OWNERSHIP ON ALL ALERTS IN SCHEMA GROCERYDBTPROJECT.GROCERY_OPS TO ROLE GROCERY_OPS_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON PROCEDURE GROCERYDBTPROJECT.GROCERY_OPS.SP_RAISE_ALERT(VARCHAR, VARCHAR, VARCHAR, VARCHAR) TO ROLE GROCERY_OPS_ROLE COPY CURRENT GRANTS;
ALTER ALERT GROCERYDBTPROJECT.GROCERY_OPS.ALERT_INGESTION_RUN RESUME;
ALTER ALERT GROCERYDBTPROJECT.GROCERY_OPS.ALERT_TASK_FAILED RESUME;
ALTER ALERT GROCERYDBTPROJECT.GROCERY_OPS.ALERT_BUDGET RESUME;
